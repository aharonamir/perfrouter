#!/usr/bin/env python3
"""
build_benchmark_weights.py
==========================
Reads task_taxonomy.json (produced by build_task_taxonomy.py) and
builds benchmark_weights.json — the weight matrix that maps each
AA benchmark to each task type.

This is not a heavy computation step — the weights were already
generated by the LLM in build_task_taxonomy.py. This script:

  1. Extracts and validates the weight matrix from the taxonomy
  2. Fills in any missing benchmark → task type entries with 0.0
  3. Exports the matrix in two formats:
       - Per-task-type: {task_type → {benchmark → weight}}
       - Per-benchmark:  {benchmark → {task_type → weight}}  (transposed)
  4. Prints a human-readable heatmap showing which benchmarks
     contribute to which task types

The weight matrix is used by build_model_features.py to compute
each model's affinity score per task type:

  affinity(model, task_type) = sum(
      benchmark_weight(benchmark, task_type)
      × model_score(benchmark)
      for each benchmark
  )

If a model has no score for a benchmark (null in model_registry.json),
that benchmark's contribution is skipped and the remaining weights
are renormalised.

Usage:
  python3 build_benchmark_weights.py
  python3 build_benchmark_weights.py --taxonomy task_taxonomy.json --out benchmark_weights.json
"""

import argparse
import json
import sys
from pathlib import Path

_PROJECT_ROOT = Path(__file__).parent.parent.parent
_DATA_DIR     = _PROJECT_ROOT / "data"


# ── All benchmarks we work with (must match fetch_aa_data.py) ────────────────
ALL_BENCHMARKS = [
    "aa_intelligence_index",
    "aa_coding_index",
    "aa_math_index",
    "bench_terminal_bench",
    "bench_tau2_bench",
    "bench_aa_lcr",
    "bench_hle",
    "bench_gpqa",
    "bench_scicode",
    "bench_ifbench",
    "bench_aime",
    "bench_livecodebench",
    "bench_mmmu_pro",
    "bench_math_500",
    # Arena ELO scores (human preference, normalised 0-1)
    "arena_text_elo",      # text quality, conversation, creative writing
    "arena_search_elo",    # search and retrieval
    "arena_code_elo",      # coding quality
    "arena_vision_elo",    # visual understanding
    "arena_document_elo",  # document understanding
]

# Human-readable short names for the heatmap display
BENCH_SHORT = {
    "aa_intelligence_index": "AA-Intel",
    "aa_coding_index":       "AA-Code",
    "aa_math_index":         "AA-Math",
    "bench_terminal_bench":  "Terminal",
    "bench_tau2_bench":      "Tau2",
    "bench_aa_lcr":          "LCR",
    "bench_hle":             "HLE",
    "bench_gpqa":            "GPQA",
    "bench_scicode":         "SciCode",
    "bench_ifbench":         "IFBench",
    "bench_aime":            "AIME",
    "bench_livecodebench":   "LiveCode",
    "bench_mmmu_pro":        "MMMU",
    "bench_math_500":        "MATH500",
    "arena_text_elo":        "Ar-Text",
    "arena_search_elo":      "Ar-Srch",
    "arena_code_elo":        "Ar-Code",
    "arena_vision_elo":      "Ar-Vis",
    "arena_document_elo":    "Ar-Doc",
}


def load_taxonomy(path: Path) -> list[dict]:
    if not path.exists():
        print(f"ERROR: {path} not found. Run build_task_taxonomy.py first.",
              file=sys.stderr)
        sys.exit(1)
    data = json.loads(path.read_text(encoding="utf-8"))
    return data.get("task_types", [])


def build_weight_matrix(task_types: list[dict]) -> dict:
    """
    Build a nested dict: {task_type_id → {benchmark → weight}}
    All benchmarks are present for every task type (missing = 0.0).
    Weights per task type sum to 1.0 (or 0.0 if no benchmarks assigned).
    """
    matrix = {}

    for t in task_types:
        tid     = t["id"]
        weights = t.get("benchmark_weights", {})

        # Build full row with 0.0 for unassigned benchmarks
        row = {b: 0.0 for b in ALL_BENCHMARKS}
        row.update({b: w for b, w in weights.items() if b in ALL_BENCHMARKS})

        # Normalise to sum=1.0
        total = sum(row.values())
        if total > 0:
            row = {b: round(w / total, 6) for b, w in row.items()}

        matrix[tid] = row

    return matrix


def transpose_matrix(matrix: dict) -> dict:
    """
    Transpose: {task_type → {benchmark → weight}}
           to: {benchmark → {task_type → weight}}
    Useful for looking up "which task types does this benchmark affect?"
    """
    transposed = {b: {} for b in ALL_BENCHMARKS}
    for task_type, weights in matrix.items():
        for benchmark, weight in weights.items():
            transposed[benchmark][task_type] = weight
    return transposed


def print_heatmap(matrix: dict, task_types: list[dict]):
    """
    Print a text heatmap showing benchmark → task type relationships.
    Cells show weight as a bar (0–5 blocks) or '·' for zero.
    """
    all_tids = [t["id"] for t in task_types]

    # Column header — benchmark short names
    col_w = 9
    header = f"{'task_type':<38}"
    for b in ALL_BENCHMARKS:
        header += f"{BENCH_SHORT[b]:>{col_w}}"
    print(header)
    print("─" * (38 + col_w * len(ALL_BENCHMARKS)))

    # One row per task type
    for tid in all_tids:
        row_weights = matrix.get(tid, {})
        is_wcb = any(t["id"] == tid and t.get("inherited_from_wcb")
                     for t in task_types)
        tag   = " *" if is_wcb else "  "
        line  = f"{tid + tag:<38}"

        for b in ALL_BENCHMARKS:
            w = row_weights.get(b, 0.0)
            if w == 0.0:
                cell = "·"
            elif w < 0.15:
                cell = "▁"
            elif w < 0.30:
                cell = "▃"
            elif w < 0.50:
                cell = "▅"
            elif w < 0.70:
                cell = "▇"
            else:
                cell = "█"
            line += f"{cell:>{col_w}}"
        print(line)

    print(f"\n  * = inherited from WildClawBench")
    print(f"  █=≥70%  ▇=50-70%  ▅=30-50%  ▃=15-30%  ▁=<15%  ·=0%")


def main():
    parser = argparse.ArgumentParser(
        description="Build benchmark weight matrix from task taxonomy"
    )
    parser.add_argument("--taxonomy", default=str(_DATA_DIR / "task_taxonomy.json"))
    parser.add_argument("--out",      default=str(_DATA_DIR / "benchmark_weights.json"))
    args = parser.parse_args()

    taxonomy_path = Path(args.taxonomy).expanduser()
    out_path      = Path(args.out).expanduser()

    # ── Load taxonomy ─────────────────────────────────────────────────────────
    print(f"Loading taxonomy from {taxonomy_path}")
    task_types = load_taxonomy(taxonomy_path)
    print(f"  {len(task_types)} task types loaded")

    # ── Build weight matrix ───────────────────────────────────────────────────
    print("\nBuilding weight matrix...")
    matrix     = build_weight_matrix(task_types)
    transposed = transpose_matrix(matrix)

    # ── Diagnostics ───────────────────────────────────────────────────────────
    print("\n── Benchmark coverage ────────────────────────────────────────────────")
    print("  (how many task types each benchmark contributes to)")
    for b in ALL_BENCHMARKS:
        nonzero = sum(1 for w in transposed[b].values() if w > 0)
        top_task = max(transposed[b].items(), key=lambda x: x[1],
                       default=("none", 0))
        bar = "█" * nonzero
        print(f"  {BENCH_SHORT[b]:<12} {nonzero:>2} task types  {bar}"
              f"   top: {top_task[0]} ({top_task[1]:.2f})")

    print("\n── Task type coverage ────────────────────────────────────────────────")
    print("  (how many benchmarks each task type uses)")
    for tid in [t["id"] for t in task_types]:
        nonzero = sum(1 for w in matrix[tid].values() if w > 0)
        max_bench = max(matrix[tid].items(), key=lambda x: x[1])
        print(f"  {tid:<45} {nonzero:>2} benchmarks  "
              f"primary: {BENCH_SHORT.get(max_bench[0], max_bench[0])} ({max_bench[1]:.2f})")

    print("\n── Weight matrix heatmap ─────────────────────────────────────────────")
    print_heatmap(matrix, task_types)

    # ── Save ──────────────────────────────────────────────────────────────────
    output = {
        "benchmarks":          ALL_BENCHMARKS,
        "task_types":          [t["id"] for t in task_types],
        "matrix":              matrix,       # task_type → {benchmark → weight}
        "matrix_transposed":   transposed,   # benchmark → {task_type → weight}
    }

    out_path.write_text(
        json.dumps(output, indent=2, ensure_ascii=False),
        encoding="utf-8"
    )

    print(f"\nSaved to: {out_path}")
    print(f"  Matrix shape: {len(matrix)} task types × {len(ALL_BENCHMARKS)} benchmarks")
    print(f"\nDone. Next step: python3 build_model_features.py")


if __name__ == "__main__":
    main()